function compileSchemas(
  artifacts: Array<[string, ContractArtifactEnvelope]>,
): Map<string, ValidateFunction> {
  const ajv = new Ajv2020({
    strict: true,
    allErrors: true,
    coerceTypes: false,
    useDefaults: false,
    removeAdditional: false,
  });
  const validators = new Map<string, ValidateFunction>();
  for (const [targetFormat, schemaFormat] of Object.entries(
    COMPILER_CONTRACT_REPAIR_SCHEMA_FORMAT_BY_TARGET,
  )) {
    const schema = artifactByFormat(artifacts, schemaFormat);
    validators.set(targetFormat, ajv.compile(schema.payload as AnySchema));
  }
  return validators;
}

function buildCompiledPlanV2Sample(): CompiledScopePlanV2Document {
  const historical = CLOSED_SCHEMA_POSITIVE_CASES.find(
    (candidate) =>
      candidate.schema_format ===
      'icarus.workflow-compiled-scope-plan-schema/1',
  )?.instance;
  if (
    !historical ||
    Array.isArray(historical) ||
    typeof historical !== 'object'
  )
    throw new CompilerContractRepairError('Missing G0.3 compiled Plan fixture');
  const cloned = strictParseJson(JSON.stringify(historical)) as JsonObject;
  cloned.format = 'icarus.workflow-graph-scope-plan/2';
  delete cloned.static_child_plan_closure_hash;
  const closureWithoutHash = { members: [], member_count: 0 };
  cloned.static_child_plan_closure = {
    ...closureWithoutHash,
    closure_hash: domainSeparatedSha256(
      'icarus:workflow-static-child-plan-closure:1\n',
      closureWithoutHash,
    ),
  };
  delete cloned.plan_hash;
  cloned.plan_hash = domainSeparatedSha256(
    'icarus:workflow-graph-plan:2\n',
    cloned,
  );
  return cloned as unknown as CompiledScopePlanV2Document;
}

