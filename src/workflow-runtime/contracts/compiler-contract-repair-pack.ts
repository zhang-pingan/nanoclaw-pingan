function validateSchemas(
  artifacts: Array<[string, ContractArtifactEnvelope]>,
): void {
  const validators = compileSchemas(artifacts);
  for (const [relativePath, artifact] of artifacts) {
    const validate = validators.get(artifact.format);
    if (validate && !validate(artifact.payload))
      throw new CompilerContractRepairError(
        `${relativePath} failed closed schema: ${JSON.stringify(validate.errors)}`,
      );
  }
  const plan = buildCompiledPlanV2Sample();
  const validatePlan = validators.get('icarus.workflow-graph-scope-plan/2')!;
  if (!validatePlan(plan))
    throw new CompilerContractRepairError(
      `Compiled IR v2 sample failed schema: ${JSON.stringify(validatePlan.errors)}`,
    );
  const lowering = artifactByFormat(
    artifacts,
    'icarus.workflow-definition-static-lowering-contract/1',
  );
  const resultWithoutHash = {
    format: 'icarus.workflow-compiler-conformance-case-result/1' as const,
    case_id: 'fixture.compiled',
    source_kind: 'workflow_definition' as const,
    source_hash: HASH,
    outcome: 'compiled' as const,
    normalized_plan: plan,
    static_lowering_contract_ref: {
      id: 'icarus.workflow-definition-static-lowering-contract',
      version: '1.0.0',
    },
    static_lowering_contract_hash: (
      lowering.payload as unknown as DefinitionStaticLoweringContractV1
    ).contract_hash,
    diagnostics: [] as [],
    proof_hashes: [] as Sha256Hash[],
    program_hashes: [] as Sha256Hash[],
  };
  const result: WorkflowCompilerConformanceCaseResultV1 = {
    ...resultWithoutHash,
    result_hash: calculateCompilerConformanceCaseResultHash(resultWithoutHash),
  };
  const validateResult = validators.get(
    'icarus.workflow-compiler-conformance-case-result/1',
  )!;
  if (!validateResult(result))
    throw new CompilerContractRepairError(
      `Conformance result sample failed schema: ${JSON.stringify(validateResult.errors)}`,
    );
  if (
    !validators.get('icarus.workflow-compiler-g2-case-input-binding/1')!(
      buildResolvedBindingSample(artifacts),
    )
  )
    throw new CompilerContractRepairError(
      'Resolved G2 binding sample failed schema',
    );
}

function validateCompiledIrDecision(
  artifacts: Array<[string, ContractArtifactEnvelope]>,
): void {
  const schema = artifactByFormat(
    artifacts,
    'icarus.workflow-compiled-scope-plan-schema/2',
  ).payload;
  assertJsonObject(schema.properties);
  assertJsonObject(schema.$defs);
  const definitions = schema.$defs;
  assertJsonObject(definitions.compiled_condition_program);
  const condition = definitions.compiled_condition_program;
  assertJsonObject(condition.properties);
  assertJsonObject(schema.properties.format);
  if (
    schema.properties.format.const !== 'icarus.workflow-graph-scope-plan/2' ||
    'static_child_plan_closure_hash' in schema.properties ||
    !('static_child_plan_closure' in schema.properties) ||
    !Array.isArray(condition.required) ||
    !condition.required.includes('operand_types') ||
    !('operand_types' in condition.properties)
  )
    throw new CompilerContractRepairError('Compiled IR v2 repair fields drift');
  assertJsonObject(definitions.compiled_node);
  if (!Array.isArray(definitions.compiled_node.oneOf))
    throw new CompilerContractRepairError('Compiled node union missing');
  const map = definitions.compiled_node.oneOf.find((candidate) => {
    assertJsonObject(candidate);
    assertJsonObject(candidate.properties);
    assertJsonObject(candidate.properties.type);
    return candidate.properties.type.const === 'map';
  });
  if (!map)
    throw new CompilerContractRepairError('Compiled map branch missing');
  assertJsonObject(map);
  assertJsonObject(map.properties);
  if (
    !Array.isArray(map.required) ||
    !map.required.includes('result_order') ||
    (map.properties.result_order as JsonObject).const !== 'item_index' ||
    !definitions.static_child_plan_closure ||
    !definitions.static_child_plan_closure_member
  )
    throw new CompilerContractRepairError('Map/closure v2 contract drift');
}

function validateStaticLowering(
  artifacts: Array<[string, ContractArtifactEnvelope]>,
): void {
  const payload = artifactByFormat(
    artifacts,
    'icarus.workflow-definition-static-lowering-contract/1',
  ).payload as unknown as DefinitionStaticLoweringContractV1;
  if (
    canonicalJson(payload.normal_named_exits) !==
      canonicalJson(['success', 'failure']) ||
    payload.engine_error.named_exit !== null ||
    payload.engine_error.transition_slot !== 'on_error' ||
    payload.local_graph_cancel.named_exit !== null ||
    payload.local_graph_cancel.transition_slot !== 'on_local_cancel' ||
    payload.global_workflow_cancel.transition_slot !== null ||
    !validateSemanticHash(
      payload,
      'contract_hash',
      'icarus:workflow-definition-static-lowering-contract:1\n',
    )
  )
    throw new CompilerContractRepairError('Static lowering outcome drift');
}

function validateDraft(
  artifacts: Array<[string, ContractArtifactEnvelope]>,
): void {
  const catalog = artifactByFormat(
    artifacts,
    'icarus.workflow-compiler-golden-draft-cases/2',
  ).payload as unknown as GoldenDraftCaseCatalogV2;
  const manifest = artifactByFormat(
    artifacts,
    'icarus.workflow-compiler-golden-draft-manifest/2',
  ).payload as unknown as GoldenDraftManifestV2;
  const historical = readHistoricalGoldenCases();
  if (
    catalog.cases.length !== 40 ||
    catalog.positive_case_count !== 10 ||
    catalog.negative_case_count !== 30 ||
    catalog.assertion_target.artifact_format !==
      'icarus.workflow-compiler-conformance-case-result/1' ||
    catalog.assertion_target.pointer_root !== '' ||
    catalog.assertion_target.hash_domain_separator !==
      COMPILER_CASE_RESULT_DOMAIN_SEPARATOR ||
    catalog.assertion_target.hash_preimage !==
      'jcs_result_without_result_hash' ||
    manifest.draft_status !== 'blocked_pending_exact_g2_identity' ||
    manifest.golden_semantic_review_status !== 'absent' ||
    manifest.sealed_bundle_status !== 'absent'
  )
    throw new CompilerContractRepairError('Golden Draft v2 status drift');
  for (const candidate of catalog.cases) {
    const prior = historical.find(
      (entry) => entry.case_id === candidate.case_id,
    );
    if (
      !prior ||
      prior.raw_source_bytes_ref !== candidate.raw_source_bytes_ref ||
      prior.raw_source_bytes_hash !== candidate.raw_source_bytes_hash ||
      prior.input_snapshot_ref !== candidate.historical_input_snapshot_ref ||
      prior.input_snapshot_hash !== candidate.historical_input_snapshot_hash ||
      candidate.g2_case_input_binding_ref !== null ||
      candidate.expected_case_result_bytes_ref !== null ||
      candidate.review_status !== 'blocked_pending_exact_g2_identity' ||
      candidate.semantic_assertions.some((assertion) =>
        assertion.subject_pointer.startsWith('/normalized/'),
      )
    )
      throw new CompilerContractRepairError(
        `Golden Draft v2 additive binding drift: ${candidate.case_id}`,
      );
  }
  const lowering = catalog.cases.find(
    (candidate) => candidate.case_id === 'positive.static-lowering',
  )!;
  const loweringExits = lowering.semantic_assertions.find(
    (assertion) => assertion.assertion_id === 'lowered-normal-named-exits',
  );
  if (
    canonicalJson(loweringExits?.expected as JsonValue) !==
    canonicalJson(['success', 'failure'])
  )
    throw new CompilerContractRepairError(
      'Golden Draft v2 lowering exits are not disjoint',
    );
  const map = catalog.cases.find(
    (candidate) => candidate.case_id === 'positive.map',
  )!;
  if (
    map.semantic_assertions[0]?.subject_pointer !==
    '/normalized_plan/nodes/1/result_order'
  )
    throw new CompilerContractRepairError('Golden Draft v2 map pointer drift');
}

function validateBindingRequirement(
  artifacts: Array<[string, ContractArtifactEnvelope]>,
): void {
  const payload = artifactByFormat(
    artifacts,
    'icarus.workflow-compiler-g2-case-input-binding-requirement/1',
  ).payload;
  if (
    payload.historical_input_snapshot_semantics !==
      'frozen_g0_stage_absence_not_g2_identity' ||
    payload.resolution_status !== 'pending_g2_compiler_implementation' ||
    payload.review_barrier !== 'blocked_until_resolved_binding_is_published' ||
    !Array.isArray(payload.case_requirements) ||
    payload.case_requirements.length !== 40 ||
    !validateSemanticHash(
      payload,
      'requirement_hash',
      'icarus:workflow-compiler-g2-case-input-binding-requirement:1\n',
    )
  )
    throw new CompilerContractRepairError('G2 additive binding drift');
  const sample = buildResolvedBindingSample(artifacts);
  const { binding_hash: sampleBindingHash, ...sampleWithoutBindingHash } =
    sample;
  if (
    sampleBindingHash !==
    calculateG2CaseInputBindingHash(sampleWithoutBindingHash)
  )
    throw new CompilerContractRepairError('G2 binding hash formula drift');
}

function validateDomainCatalog(
  artifacts: Array<[string, ContractArtifactEnvelope]>,
  manifest: ContractArtifactEnvelope,
): void {
  const domain = artifactByFormat(
    artifacts,
    'icarus.workflow-compiler-contract-repair-domain-separators/1',
  );
  const entries = domain.payload.entries;
  if (!Array.isArray(entries))
    throw new CompilerContractRepairError('Repair domain catalog missing');
  const formats = new Set<string>();
  for (const entry of entries) {
    assertJsonObject(entry);
    if (formats.has(String(entry.format)))
      throw new CompilerContractRepairError(
        `Duplicate repair domain format: ${entry.format}`,
      );
    formats.add(String(entry.format));
  }
  const required = [
    manifest.format,
    'icarus.workflow-graph-scope-plan/2',
    'icarus.workflow-condition-program/2',
    'icarus.workflow-static-child-plan-closure/1',
    'icarus.workflow-compiler-conformance-case-result/1',
    'icarus.workflow-compiler-effective-case-input/1',
    'icarus.workflow-compiler-g2-case-input-binding/1',
  ];
  if (required.some((format) => !formats.has(format)))
    throw new CompilerContractRepairError('Repair domain coverage drift');
}

function listRepairFiles(): string[] {
  const root = absoluteContractPath(COMPILER_CONTRACT_REPAIR_ROOT);
  if (!fs.existsSync(root)) return [];
  const files: string[] = [];
  const visit = (directory: string): void => {
    for (const name of fs.readdirSync(directory).sort()) {
      const absolute = path.join(directory, name);
      const stat = fs.lstatSync(absolute);
      if (stat.isSymbolicLink())
        throw new CompilerContractRepairError(
          `Repair tree contains symlink: ${absolute}`,
        );
      if (stat.isDirectory()) visit(absolute);
      else if (stat.isFile())
        files.push(
          path.relative(contractsRoot, absolute).split(path.sep).join('/'),
        );
      else
        throw new CompilerContractRepairError(
          `Repair tree contains unsupported entry: ${absolute}`,
        );
    }
  };
  visit(root);
  return files.sort();
}

function validateBoundaries(
  artifacts: Array<[string, ContractArtifactEnvelope]>,
  checkTree: boolean,
): void {
  assertHistoricalCompilerContractInputs();
  if (checkTree) {
    const expected = artifacts
      .map(([relativePath]) => relativePath)
      .concat(COMPILER_CONTRACT_REPAIR_MANIFEST_PATH)
      .sort();
    if (canonicalJson(listRepairFiles()) !== canonicalJson(expected))
      throw new CompilerContractRepairError('Repair generated tree drift');
  }
  const sealed = fs.readdirSync(absoluteContractPath('conformance/sealed'));
  const packageJson = strictParseJsonBytes(
    fs.readFileSync(path.join(repoRoot, 'package.json')),
  );
  assertJsonObject(packageJson);
  assertJsonObject(packageJson.scripts);
  if (
    sealed.length !== 1 ||
    sealed[0] !== '.gitkeep' ||
    fs.existsSync(path.join(workflowRuntimeRoot, 'compiler')) ||
    'test:g2' in packageJson.scripts ||
    packageJson.scripts['test:g2:contract'] !==
      'vitest run src/workflow-runtime/contracts/compiler-contract-repair.test.ts'
  )
    throw new CompilerContractRepairError(
      'Compiler implementation or Golden seal boundary crossed',
    );
  const forbidden = [
    'registry',
    'authoring',
    'runtime/graph-runtime.ts',
    'projection/runtime-center-api.ts',
  ];
  if (
    forbidden.some((candidate) =>
      fs.existsSync(path.join(workflowRuntimeRoot, candidate)),
    )
  )
    throw new CompilerContractRepairError('G3+ boundary crossed');
}

function validateManifest(
  artifacts: Array<[string, ContractArtifactEnvelope]>,
  manifest: ContractArtifactEnvelope,
): void {
  if (
    manifest.payload.r016_status !== 'CLOSED' ||
    manifest.payload.g2_status !== 'READY' ||
    manifest.payload.production_compiler_status !== 'absent' ||
    manifest.payload.golden_semantic_review_status !== 'absent' ||
    manifest.payload.golden_seal_status !== 'not_run' ||
    manifest.payload.historical_g0_3_manifest_hash !==
      HISTORICAL_G0_3_MANIFEST_HASH ||
    manifest.payload.historical_g0_8_manifest_hash !==
      HISTORICAL_G0_8_MANIFEST_HASH ||
    canonicalJson(buildManifest(artifacts)) !== canonicalJson(manifest)
  )
    throw new CompilerContractRepairError('Repair root manifest drift');
}

function validatePack(
  artifacts: Array<[string, ContractArtifactEnvelope]>,
  manifest: ContractArtifactEnvelope,
  checkTree: boolean,
): void {
  for (const [, artifact] of artifacts) parseContractArtifactEnvelope(artifact);
  validateSchemas(artifacts);
  validateCompiledIrDecision(artifacts);
  validateStaticLowering(artifacts);
  validateDraft(artifacts);
  validateBindingRequirement(artifacts);
  validateDomainCatalog(artifacts, manifest);
  validateBoundaries(artifacts, checkTree);
  validateManifest(artifacts, manifest);
}

export function generateContractPackCompilerContractRepair(): ContractArtifactEnvelope {
  const artifacts = expectedArtifacts();
  const manifest = buildManifest(artifacts);
  validatePack(artifacts, manifest, false);
  for (const [relativePath, artifact] of artifacts)
    writeAtomic(relativePath, renderJson(artifact));
  writeAtomic(COMPILER_CONTRACT_REPAIR_MANIFEST_PATH, renderJson(manifest));
  validatePack(artifacts, manifest, true);
  return manifest;
}

