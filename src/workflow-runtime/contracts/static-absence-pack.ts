function artifactDescriptor(
  artifactPath: string,
  artifact: ContractArtifactEnvelope,
): JsonObject {
  return {
    path: artifactPath,
    format: artifact.format,
    ref: artifact.ref,
    version: artifact.version,
    domain_separator: artifact.domain_separator,
    hash: artifact.hash,
  };
}

function findPayload<T extends JsonObject>(
  artifacts: Array<[string, ContractArtifactEnvelope]>,
  format: string,
): T {
  const artifact = artifacts.find(
    ([, candidate]) => candidate.format === format,
  )?.[1];
  if (!artifact)
    throw new StaticAbsencePackError(`Missing G0.7 artifact ${format}`);
  return artifact.payload as T;
}

