function artifactDescriptor(
  artifactPath: string,
  artifact: ContractArtifactEnvelope,
): JsonObject {
  return {
    path: artifactPath,
    format: artifact.format,
    ref: artifact.ref,
    version: artifact.version,
    domain_separator: artifact.domain_separator,
    hash: artifact.hash,
  };
}

function buildManifest(
  artifacts: Array<[string, ContractArtifactEnvelope]>,
): ContractArtifactEnvelope {
  const schemaFormats = CLOSED_SCHEMA_DESCRIPTORS.map(
    (descriptor) => descriptor.artifact_format,
  ).sort(asciiCompare);
  return buildArtifact(
    'icarus.workflow-contract-pack-closed-schemas/1',
    'icarus.workflow-contract-pack-closed-schemas',
    'icarus:workflow-contract-pack-closed-schemas:1\n',
    {
      gate: 'G0.3',
      status: 'closed_schemas',
      foundation_manifest_hash: foundationManifestHash,
      schema_formats: schemaFormats,
      schema_targets: CLOSED_SCHEMA_DESCRIPTORS.map((descriptor) => ({
        artifact_path: descriptor.artifact_path,
        artifact_format: descriptor.artifact_format,
        target_contract: descriptor.target_format,
      })).sort((left, right) =>
        asciiCompare(left.artifact_format, right.artifact_format),
      ),
      positive_case_count: CLOSED_SCHEMA_POSITIVE_CASES.length,
      negative_case_count: CLOSED_SCHEMA_NEGATIVE_CASES.length,
      artifacts: artifacts
        .map(([artifactPath, artifact]) =>
          artifactDescriptor(artifactPath, artifact),
        )
        .sort((left, right) =>
          asciiCompare(String(left.path), String(right.path)),
        ),
      future_reserved_directories: [...recordedFutureReservedDirectories],
    },
  );
}

