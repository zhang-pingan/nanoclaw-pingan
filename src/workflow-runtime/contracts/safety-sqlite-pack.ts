function validateClosedObjects(value: JsonValue, pointer = ''): void {
  if (Array.isArray(value)) {
    value.forEach((child, index) =>
      validateClosedObjects(child, `${pointer}/${index}`),
    );
    return;
  }
  if (value === null || typeof value !== 'object') return;
  const objectValue = value as JsonObject;
  if (
    objectValue.type === 'object' &&
    objectValue.additionalProperties !== false
  ) {
    throw new SafetySqliteContractError(
      `Open G0.5 object schema at ${pointer || '/'}`,
    );
  }
  for (const [key, child] of Object.entries(objectValue)) {
    validateClosedObjects(child, `${pointer}/${key}`);
  }
}

function compileSchemas(artifacts: Array<[string, ContractArtifactEnvelope]>): {
  ajv: Ajv2020;
  validators: Map<string, ReturnType<Ajv2020['compile']>>;
  schemasByTarget: Map<string, JsonObject>;
} {
  const ajv = new Ajv2020({
    allErrors: true,
    coerceTypes: false,
    removeAdditional: false,
    strict: true,
    useDefaults: false,
  });
  const validators = new Map<string, ReturnType<Ajv2020['compile']>>();
  const schemasByTarget = new Map<string, JsonObject>();
  for (const descriptor of SAFETY_SQLITE_ARTIFACT_DESCRIPTORS.filter(
    (candidate) => candidate.artifact_kind === 'schema',
  )) {
    const artifact = artifacts.find(
      ([artifactPath]) => artifactPath === descriptor.artifact_path,
    )?.[1];
    if (!artifact || descriptor.target_format === null) {
      throw new Error(
        `Missing G0.5 schema artifact ${descriptor.artifact_path}`,
      );
    }
    validateClosedObjects(artifact.payload);
    schemasByTarget.set(descriptor.target_format, artifact.payload);
    validators.set(
      descriptor.target_format,
      ajv.compile(artifact.payload as AnySchema),
    );
  }
  validateTypeScriptSchemaConformance(schemasByTarget);
  return { ajv, validators, schemasByTarget };
}

function cloneObject(value: JsonObject): JsonObject {
  const clone = strictParseJson(JSON.stringify(value));
  assertJsonObject(clone);
  return clone;
}

function pointerTokens(pointer: string): string[] {
  if (!pointer.startsWith('/')) {
    throw new Error(`Fixture JSON pointer must be absolute: ${pointer}`);
  }
  return pointer
    .slice(1)
    .split('/')
    .map((token) => token.replaceAll('~1', '/').replaceAll('~0', '~'));
}

function applyMutation(
  payload: JsonObject,
  mutation: SafetySqliteMutation,
): void {
  const tokens = pointerTokens(mutation.pointer);
  const finalToken = tokens.pop();
  if (finalToken === undefined)
    throw new Error('Fixture pointer cannot be empty');
  let current: JsonValue = payload;
  for (const token of tokens) {
    if (Array.isArray(current)) current = current[Number(token)]!;
    else {
      assertJsonObject(current);
      current = current[token]!;
    }
  }
  if (Array.isArray(current)) {
    const index = Number(finalToken);
    if (mutation.operation === 'remove') current.splice(index, 1);
    else if (mutation.operation === 'add')
      current.splice(index, 0, mutation.value);
    else current[index] = mutation.value;
    return;
  }
  assertJsonObject(current);
  if (mutation.operation === 'remove') delete current[finalToken];
  else current[finalToken] = mutation.value;
}

function expectedSchemaError(
  errors: ErrorObject[] | null | undefined,
  testCase: SafetySqliteNegativeCase,
): boolean {
  return Boolean(
    errors?.some(
      (error) =>
        error.keyword === testCase.expected_keyword &&
        error.instancePath === testCase.expected_instance_pointer,
    ),
  );
}

function withoutKey(objectValue: JsonObject, key: string): JsonObject {
  return Object.fromEntries(
    Object.entries(objectValue).filter(([candidate]) => candidate !== key),
  );
}

function validateCapacitySemantic(payload: JsonObject): void {
  const expectedHash = domainSeparatedSha256(
    'icarus:deployment-runtime-capacity:1\n',
    withoutKey(payload, 'config_hash'),
  );
  if (
    payload.config_hash !== expectedHash ||
    Number(payload.soft_blob_high_water_bytes) >=
      Number(payload.max_physical_blob_bytes)
  ) {
    throw new SafetySqliteContractError(
      'Deployment Capacity hash or blob watermark invariant drift',
    );
  }
}

