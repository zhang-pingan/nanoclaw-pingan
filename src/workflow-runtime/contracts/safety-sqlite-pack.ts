function assertKeyset(
  actual: readonly string[],
  expected: readonly string[],
  label: string,
): void {
  const actualSorted = [...actual].sort(asciiCompare);
  const expectedSorted = [...expected].sort(asciiCompare);
  if (actualSorted.join('\n') !== expectedSorted.join('\n')) {
    throw new SafetySqliteContractError(`${label} TypeScript/schema key drift`);
  }
}

