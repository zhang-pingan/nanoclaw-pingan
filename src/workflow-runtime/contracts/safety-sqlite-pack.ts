function asciiCompare(left: string, right: string): number {
  return left < right ? -1 : left > right ? 1 : 0;
}

function absoluteContractPath(relativePath: string): string {
  const absolute = path.resolve(contractsRoot, relativePath);
  if (!absolute.startsWith(`${contractsRoot}${path.sep}`)) {
    throw new Error(`Contract path escapes root: ${relativePath}`);
  }
  return absolute;
}

function absoluteRepositoryPath(relativePath: string): string {
  const absolute = path.resolve(repositoryRoot, relativePath);
  if (!absolute.startsWith(`${repositoryRoot}${path.sep}`)) {
    throw new Error(`Repository path escapes root: ${relativePath}`);
  }
  return absolute;
}

function renderJson(value: JsonValue): string {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function writeAtomicFile(absoluteFile: string, value: JsonValue): void {
  fs.mkdirSync(path.dirname(absoluteFile), { recursive: true });
  const temporary = `${absoluteFile}.tmp-${process.pid}`;
  fs.writeFileSync(temporary, renderJson(value), {
    encoding: 'utf8',
    mode: 0o644,
  });
  fs.renameSync(temporary, absoluteFile);
}

function writeContractArtifact(
  relativePath: string,
  artifact: ContractArtifactEnvelope,
): void {
  writeAtomicFile(absoluteContractPath(relativePath), artifact);
}

function assertExpectedContractBytes(
  relativePath: string,
  expected: ContractArtifactEnvelope,
): void {
  const actual = fs.readFileSync(absoluteContractPath(relativePath), 'utf8');
  if (actual !== renderJson(expected)) {
    throw new Error(
      `${relativePath} is not generated byte-for-byte; run npm run contracts:generate`,
    );
  }
}

function readArtifact(relativePath: string): ContractArtifactEnvelope {
  return parseContractArtifactEnvelope(
    strictParseJsonBytes(fs.readFileSync(absoluteContractPath(relativePath))),
  );
}

