function artifactByFormat(
  artifacts: Array<[string, ContractArtifactEnvelope]>,
  format: string,
): ContractArtifactEnvelope {
  const artifact = artifacts.find(
    ([, candidate]) => candidate.format === format,
  )?.[1];
  if (!artifact)
    throw new CapacityControlPlaneContractError(
      `Missing G0.10 artifact: ${format}`,
    );
  return artifact;
}

function payloadByFormat<T>(
  artifacts: Array<[string, ContractArtifactEnvelope]>,
  format: string,
): T {
  return artifactByFormat(artifacts, format).payload as unknown as T;
}

