function keyset(
  actual: string[],
  expected: readonly string[],
  label: string,
): void {
  if (canonicalJson(actual.sort()) !== canonicalJson([...expected].sort()))
    throw new CapacityControlPlaneContractError(
      `${label} TypeScript keyset drift`,
    );
}

function compileSchemas(
  artifacts: Array<[string, ContractArtifactEnvelope]>,
): Map<string, ValidateFunction> {
  const ajv = new Ajv2020({
    strict: true,
    allErrors: true,
    coerceTypes: false,
    useDefaults: false,
    removeAdditional: false,
  });
  const result = new Map<string, ValidateFunction>();
  for (const [targetFormat, schemaFormat] of Object.entries(
    CAPACITY_CONTROL_PLANE_SCHEMA_FORMAT_BY_TARGET,
  )) {
    const schema = artifactByFormat(artifacts, schemaFormat);
    result.set(targetFormat, ajv.compile(schema.payload as AnySchema));
  }
  return result;
}

