function validateDomainCatalog(
  artifacts: Array<[string, ContractArtifactEnvelope]>,
  manifest: ContractArtifactEnvelope,
): void {
  const domain = artifactByFormat(
    artifacts,
    'icarus.workflow-capacity-control-plane-domain-separators/1',
  );
  const entries = domain.payload.entries;
  if (!Array.isArray(entries))
    throw new CapacityControlPlaneContractError(
      'Capacity domain registry missing',
    );
  const actual = new Map<string, string>();
  for (const entry of entries) {
    assertJsonObject(entry);
    if (actual.has(String(entry.format)))
      throw new CapacityControlPlaneContractError(
        `Duplicate Capacity domain format: ${entry.format}`,
      );
    actual.set(String(entry.format), String(entry.domain_separator));
  }
  const expected = new Map([
    ...artifacts.map(
      ([, artifact]) => [artifact.format, artifact.domain_separator] as const,
    ),
    [manifest.format, manifest.domain_separator] as const,
    [
      'icarus.deployment-runtime-capacity-publication/1',
      'icarus:deployment-runtime-capacity-publication:1\n',
    ] as const,
    [
      'icarus.capacity-admin-command-request/1',
      'icarus:capacity-admin-command-request:1\n',
    ] as const,
  ]);
  if (
    actual.size !== expected.size ||
    [...expected].some(
      ([format, domainValue]) => actual.get(format) !== domainValue,
    )
  )
    throw new CapacityControlPlaneContractError(
      'Capacity domain coverage drift',
    );
}

function listAddendumFiles(): string[] {
  const root = absoluteContractPath(addendumRoot);
  if (!fs.existsSync(root)) return [];
  const files: string[] = [];
  const visit = (directory: string): void => {
    for (const name of fs.readdirSync(directory).sort()) {
      const absolute = path.join(directory, name);
      const stat = fs.lstatSync(absolute);
      if (stat.isSymbolicLink())
        throw new CapacityControlPlaneContractError(
          `Capacity addendum contains symlink: ${absolute}`,
        );
      if (stat.isDirectory()) visit(absolute);
      else if (stat.isFile())
        files.push(
          path.relative(contractsRoot, absolute).split(path.sep).join('/'),
        );
      else
        throw new CapacityControlPlaneContractError(
          `Capacity addendum contains unsupported entry: ${absolute}`,
        );
    }
  };
  visit(root);
  return files.sort();
}

function validateBoundaries(
  artifacts: Array<[string, ContractArtifactEnvelope]>,
  checkTree: boolean,
): void {
  assertHistoricalG0_9Conformance();
  if (checkTree) {
    const expected = artifacts
      .map(([relativePath]) => relativePath)
      .filter((relativePath) => relativePath.startsWith(`${addendumRoot}/`))
      .concat(manifestPath)
      .sort();
    if (canonicalJson(listAddendumFiles()) !== canonicalJson(expected))
      throw new CapacityControlPlaneContractError(
        'Capacity addendum generated tree drift',
      );
  }
  const sealed = fs.readdirSync(absoluteContractPath('conformance/sealed'));
  const forbiddenPaths = [
    'store/runtime-store.ts',
    'store/schema/workflow-runtime-schema-v1.sql',
    'runtime/capacity-admin.ts',
    'runtime/capacity-publication.ts',
    'runtime/scheduler.ts',
    'projection/runtime-center-api.ts',
    'projection/runtime-center-renderer',
  ];
  if (
    sealed.length !== 1 ||
    sealed[0] !== '.gitkeep' ||
    forbiddenPaths.some((relativePath) =>
      fs.existsSync(path.join(workflowRuntimeRoot, relativePath)),
    ) ||
    fs.existsSync(
      path.join(
        repoRoot,
        'data/workflow-runtime/workflow-runtime-capacity.json',
      ),
    )
  )
    throw new CapacityControlPlaneContractError(
      'G0.10 forbidden implementation boundary crossed',
    );
  const packageJson = strictParseJsonBytes(
    fs.readFileSync(path.join(repoRoot, 'package.json')),
  );
  assertJsonObject(packageJson);
  const scripts = packageJson.scripts;
  assertJsonObject(scripts);
  if (
    scripts['test:g0.9'] !==
      'vitest run src/workflow-runtime/contracts/g0-conformance.test.ts' ||
    scripts['test:g0.10'] !==
      'vitest run src/workflow-runtime/contracts/capacity-control-plane.test.ts' ||
    typeof scripts['test:g0'] !== 'string' ||
    !scripts['test:g0'].includes('capacity-control-plane.test.ts')
  )
    throw new CapacityControlPlaneContractError(
      'Current G0.10 conformance entrypoint missing',
    );
}

